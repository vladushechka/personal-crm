const TRANSLIT: Record<string, string> = {
  а: "a", б: "b", в: "v", г: "g", д: "d", е: "e", ё: "e", ж: "zh", з: "z", и: "i", й: "y",
  к: "k", л: "l", м: "m", н: "n", о: "o", п: "p", р: "r", с: "s", т: "t", у: "u", ф: "f",
  х: "kh", ц: "ts", ч: "ch", ш: "sh", щ: "shch", ъ: "", ы: "y", ь: "", э: "e", ю: "yu", я: "ya",
};

function transliterate(value: string) {
  return [...value.toLowerCase()].map((char) => TRANSLIT[char] ?? char).join("");
}

function feminineSurname(surname: string) {
  if (/(ов|ёв|ев|ин|ын)$/.test(surname)) return `${surname}а`;
  if (/(ский|цкий)$/.test(surname)) return surname.replace(/ий$/, "ая");
  return surname; // Ким, Шевченко, Черных do not change
}

// mulberry32: small fast seeded PRNG
function createRandom(seed: number) {
  let state = seed >>> 0;
  const next = () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  return {
    next,
    int: (min: number, max: number) => min + Math.floor(next() * (max - min + 1)),
    pick: <T>(items: readonly T[]): T => items[Math.floor(next() * items.length)],
    chance: (probability: number) => next() < probability,
  };
}

type Random = ReturnType<typeof createRandom>;

function digits(random: Random, count: number) {
  return Array.from({ length: count }, () => random.int(0, 9)).join("");
}

function fakePhone(random: Random) {
  return `+7 9${digits(random, 2)} ${digits(random, 3)}-${digits(random, 2)}-${digits(random, 2)}`;
}

function fakeEmail(random: Random, firstName: string, surname: string, index: number) {
  const first = transliterate(firstName);
  const last = transliterate(surname);
  const local = random.pick([
    `${first}.${last}`,
    `${first[0]}.${last}`,
    `${last}.${first}`,
    `${first}${last}${random.int(1, 99)}`,
    `${last}${index}`,
  ]);
  return `${local}@${random.pick(EMAIL_DOMAINS)}`;
}

// Past-tense verb ending agreeing with the contact's gender: "обещал" / "обещала"
function past(gender: Gender, stem: string) {
  return gender === "female" ? `${stem}а` : stem;
}

