function randomDateBetween(random: Random, from: number, to: number) {
  return new Date(from + random.next() * (to - from));
}

const DAY_MS = 24 * 60 * 60 * 1000;

export function generateFakeContacts(count: number, { seed = 20261014, now = Date.now() } = {}) {
  const random = createRandom(seed);
  const threeYearsAgo = now - 3 * 365 * DAY_MS;

  const people = Array.from({ length: count }, () => {
    const gender: Gender = random.chance(0.5) ? "male" : "female";
    const firstName = random.pick(gender === "male" ? MALE_FIRST_NAMES : FEMALE_FIRST_NAMES);
    const maleSurname = random.pick(SURNAMES);
    const surname = gender === "male" ? maleSurname : feminineSurname(maleSurname);
    return { gender, firstName, surname, name: `${firstName} ${surname}` };
  });

  return people.map((person, index): FakeContact => {
    const createdAt = randomDateBetween(random, threeYearsAgo, now - DAY_MS);

    const noteCount = random.pick([0, 0, 0, 1, 1, 1, 1, 2, 2, 3, 4]);
    const notes = Array.from({ length: noteCount }, () => ({
      body: fakeNoteBody(random, person.gender),
      createdAt: randomDateBetween(random, createdAt.getTime(), now),
    }));

    return {
      contact: {
        name: person.name,
        about: random.chance(0.85) ? random.pick(ABOUT) : null,
        howWeMet: random.chance(0.9) ? random.pick(HOW_WE_MET) : null,
        phone: random.chance(0.9) ? fakePhone(random) : null,
        email: random.chance(0.7)
          ? fakeEmail(random, person.firstName, person.surname, index + 1)
          : null,
        createdAt,
      },
      notes,
    };
  });
}
